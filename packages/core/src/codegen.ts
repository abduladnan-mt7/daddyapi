import type { FieldSpec, Fields, Resource, SiteSpec } from '@daddyapi/spec';
import { fieldValueType, resourceDataSchema } from './openapi';
import { resourceInputs } from './params';

/** "author-page" → "AuthorPage". */
export function pascalCase(name: string): string {
  return name
    .split(/[^a-zA-Z0-9]+/)
    .filter(Boolean)
    .map((part) => part[0]!.toUpperCase() + part.slice(1))
    .join('')
    .replace(/^(\d)/, '_$1');
}

/** "author-page" → "authorPage". */
export function camelCase(name: string): string {
  const pascal = pascalCase(name);
  return pascal[0]!.toLowerCase() + pascal.slice(1);
}

/**
 * Make spec text safe inside a generated comment: no line breaks (which would
 * end a line comment) and no star-slash (which would end a block comment).
 */
export function commentSafe(text: string): string {
  return text.replace(/\s+/g, ' ').replace(/\*\//g, '*\\/');
}

function tsField(spec: FieldSpec): string {
  const scalar = fieldValueType(spec);
  const many = typeof spec !== 'string' && spec.many;
  if (scalar === 'unknown') return many ? 'unknown[] | null' : 'unknown';
  return `${many ? `${scalar}[]` : scalar} | null`;
}

function quoteKey(key: string): string {
  return /^[A-Za-z_$][\w$]*$/.test(key) ? key : JSON.stringify(key);
}

function rowInterface(name: string, fields: Fields, doc?: string): string {
  const lines = Object.entries(fields).map(([key, spec]) => `  ${quoteKey(key)}: ${tsField(spec)};`);
  const comment = doc ? `/** ${commentSafe(doc)} */\n` : '';
  return `${comment}export interface ${name} {\n${lines.join('\n')}\n}`;
}

function paramsInterface(resource: Resource, typeName: string): string {
  const inputs = resourceInputs(resource);
  const lines: string[] = [];
  for (const p of inputs.pathParams) lines.push(`  ${quoteKey(p)}: string | number;`);
  if (inputs.paginated) lines.push('  /** How many pages to fetch. */\n  pages?: number;');
  if (inputs.isList) {
    lines.push('  /** Return at most this many rows. */\n  limit?: number;');
    lines.push('  /** Skip this many rows first. */\n  offset?: number;');
  }
  const fieldUnion = inputs.fieldNames.map((f) => JSON.stringify(f)).join(' | ') || 'string';
  lines.push(`  /** Only return these fields. */\n  fields?: Array<${fieldUnion}>;`);
  return `export interface ${typeName}Params {\n${lines.join('\n')}\n}`;
}

/**
 * Generate a self-contained TypeScript module for a SiteSpec: one interface per
 * resource, a params type per resource, and a small typed client for the API
 * that `daddyapi dev` serves. No runtime dependencies (uses global fetch).
 */
export function generateTypeScript(spec: SiteSpec): string {
  const out: string[] = [
    `// Generated by daddyapi from the "${commentSafe(spec.name)}" spec (${commentSafe(spec.baseUrl)}).`,
    '// Do not edit by hand: regenerate with `daddyapi types <spec> --out <file>`.',
    '',
    '/** Extraction warnings: fields that could not be found on the page. */',
    'export interface Warning {\n  field: string;\n  message: string;\n}',
    '',
    '/** Response metadata. */',
    'export interface Meta {\n  resource: string;\n  source: string;\n  pages: number;\n  fromCache: boolean;\n  fetchedAt: string;\n  total?: number;\n  returned?: number;\n  offset?: number;\n  limit?: number;\n  fields?: string[];\n}',
    '',
    '/** Every endpoint answers { data, warnings, meta }. */',
    'export interface Envelope<T> {\n  data: T;\n  warnings: Warning[];\n  meta: Meta;\n}',
    '',
    '/** Error body returned with a non-2xx status. */',
    'export interface ApiErrorBody {\n  error: { code: string; message: string; param?: string };\n  requestId: string;\n}',
    '',
    'export class ApiError extends Error {\n  constructor(\n    readonly status: number,\n    readonly code: string,\n    message: string,\n    readonly requestId?: string,\n  ) {\n    super(message);\n    this.name = \'ApiError\';\n  }\n}',
  ];

  const methods: string[] = [];
  for (const resource of spec.resources) {
    const type = pascalCase(resource.name);
    const fields = resource.list?.fields ?? resource.item?.fields ?? {};
    const rowType = resource.list ? `${type}Row` : type;
    out.push('', rowInterface(rowType, fields, resource.description), '', paramsInterface(resource, type));
    const dataType = resource.list ? `${rowType}[]` : rowType;
    const needsParams = resourceInputs(resource).pathParams.length > 0;
    const doc = resource.description ? `  /** ${commentSafe(resource.description)} */\n` : '';
    methods.push(
      `${doc}  ${camelCase(resource.name)}(params${needsParams ? '' : '?'}: ${type}Params): Promise<Envelope<${dataType}>> {\n` +
        `    return this.get('/${resource.name}', params);\n  }`,
    );
  }

  out.push(
    '',
    'export interface ClientOptions {\n  /** Sent as "Authorization: Bearer <apiKey>" when the server requires a key. */\n  apiKey?: string;\n  /** Custom fetch, e.g. for tests or older runtimes. */\n  fetch?: typeof fetch;\n}',
    '',
    `/** Typed client for the "${commentSafe(spec.name)}" API served by \`daddyapi dev\`. */`,
    `export class ${pascalCase(spec.name)}Client {\n` +
      '  private readonly baseUrl: string;\n' +
      '  private readonly fetchImpl: typeof fetch;\n\n' +
      '  constructor(\n    baseUrl: string,\n    private readonly options: ClientOptions = {},\n  ) {\n' +
      "    this.baseUrl = baseUrl.replace(/\\/+$/, '');\n" +
      '    this.fetchImpl = options.fetch ?? fetch;\n  }\n\n' +
      '  private async get<T>(path: string, params: object = {}): Promise<T> {\n' +
      '    const query = new URLSearchParams();\n' +
      '    for (const [key, value] of Object.entries(params)) {\n' +
      '      if (value === undefined || value === null) continue;\n' +
      "      query.set(key, Array.isArray(value) ? value.join(',') : String(value));\n" +
      '    }\n' +
      "    const qs = query.toString();\n" +
      "    const headers: Record<string, string> = { Accept: 'application/json' };\n" +
      "    if (this.options.apiKey) headers.Authorization = `Bearer ${this.options.apiKey}`;\n" +
      "    const res = await this.fetchImpl(`${this.baseUrl}${path}${qs ? `?${qs}` : ''}`, { headers });\n" +
      '    if (!res.ok) {\n' +
      '      const body = (await res.json().catch(() => undefined)) as ApiErrorBody | undefined;\n' +
      "      throw new ApiError(res.status, body?.error.code ?? 'http-error', body?.error.message ?? res.statusText, body?.requestId);\n" +
      '    }\n' +
      '    return (await res.json()) as T;\n' +
      '  }\n\n' +
      methods.join('\n\n') +
      '\n}',
    '',
  );
  return out.join('\n');
}

/** JSON Schema (draft 2020-12) for every resource's data, keyed by resource name. */
export function generateJsonSchema(spec: SiteSpec): Record<string, unknown> {
  const defs: Record<string, unknown> = {};
  for (const resource of spec.resources) {
    defs[pascalCase(resource.name)] = {
      description: resource.description,
      ...resourceDataSchema(resource),
    };
  }
  return {
    $schema: 'https://json-schema.org/draft/2020-12/schema',
    title: `${spec.name} data`,
    description: `Data shapes for the "${spec.name}" daddyapi spec (${spec.baseUrl})`,
    $defs: defs,
  };
}
